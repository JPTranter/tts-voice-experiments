#!/usr/bin/env python
"""Regenerate the README's sample catalog between its BEGIN/END markers.

Every audio example gets a relative markdown link, which on GitHub opens the file's
blob view with GitHub's built-in audio player - so a reader can play each take
straight from the README without downloading anything.

Run after adding renders:  python tools_gen_catalog.py
Validation: the script fails if a link target does not exist, so the catalog can never
point at a file that is not in the repo.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN: sample-catalog (generated by tools_gen_catalog.py) -->"
END = "<!-- END: sample-catalog -->"
SKIP_DIRS = {"renders", "raw", "parts", "_speed_probe", "emotion_probe"}


def duration_map() -> dict[str, float]:
    inv = ROOT / "results" / "sample_inventory.json"
    if inv.exists():
        return {r["path"]: r["seconds"] for r in json.loads(inv.read_text(encoding="utf-8"))}
    return {}


DUR = duration_map()


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


SLUG = git("remote", "get-url", "origin").rstrip("/").removesuffix(".git").split("github.com")[-1].lstrip("/:")
OWNER, _, REPO = SLUG.partition("/")
BRANCH = git("rev-parse", "--abbrev-ref", "HEAD") or "master"
# jsDelivr serves content-type audio/mpeg WITHOUT content-disposition, so a click plays in the
# browser. The alternatives do not: the blob page has no player, and raw.githubusercontent.com
# forces a download. See docs/github-audio-embedding.md.
CDN = f"https://cdn.jsdelivr.net/gh/{OWNER}/{REPO}@{BRANCH}"
PAGES = f"https://{OWNER.lower()}.github.io/{REPO}/players.html"
SAMPLE_PAGE = f"https://{OWNER.lower()}.github.io/{REPO}/s"


def page_link(rel: str, text: str) -> str:
    """Link a sample's label to its own page (player, transcript, measurements). The ▶ links point
    at the audio itself for immediate playback; the label goes to the context page."""
    stem = Path(rel).stem
    return f'[{text}]({SAMPLE_PAGE}/{stem}.html "player, transcript and measurements")'


def secs(rel: str) -> str:
    s = DUR.get(rel)
    if s is None and (ROOT / rel).exists():
        out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                              "-of", "csv=p=0", str(ROOT / rel)], capture_output=True, text=True)
        try:
            s = round(float(out.stdout.strip()), 1)
        except ValueError:
            s = None
    return f"{s:g} s" if s else "?"


def play(rel: str, style: str = "▶") -> str:
    if not (ROOT / rel).exists():
        raise SystemExit(f"catalog link target does not exist: {rel}")
    return f'[{style} {secs(rel)}]({CDN}/{rel} "{rel}")'  # title = repo path, on hover


def play_if(rel: str, style: str = "▶") -> str:
    """Like play(), but renders an em dash when the take was never made — the catalog must
    describe the repo that exists, and a missing render must not break regeneration."""
    return play(rel, style) if (ROOT / rel).exists() else "—"


def voices(prefix: str, pattern: str) -> list[str]:
    """Voice names discovered from the audio itself, so the tables cannot drift from the files."""
    out = []
    for p in sorted((ROOT / prefix).glob(pattern)):
        name = p.name
        name = name.replace("en-f-", "").replace("en-m-", "").replace("en-", "")
        name = name.replace("-emotion-fast150.mp3", "").replace("-emotion.mp3", "")
        name = name.replace("-fast150.mp3", "").replace(".mp3", "")
        out.append(name)
    return out


def english_table() -> str:
    rows = []
    for p in sorted((ROOT / "audio/english_female").glob("*.mp3")):
        v = p.stem.replace("en-f-", "")
        rows.append(f"| {page_link(f'audio/english_female/{p.name}', v)} | F | {play(f'audio/english_female/{p.name}')} | "
                    f"{play(f'audio/english_female_fast/en-f-{v}-fast150.mp3')} | "
                    f"{play_if(f'audio/emotion/en-{v}-emotion.mp3')} | "
                    f"{play_if(f'audio/emotion/en-{v}-emotion-fast150.mp3')} |")
    for p in sorted((ROOT / "audio/english_male").glob("*.mp3")):
        v = p.stem.replace("en-m-", "")
        rows.append(f"| {page_link(f'audio/english_male/{p.name}', v)} | M | {play(f'audio/english_male/{p.name}')} | "
                    f"{play(f'audio/english_male_fast/en-m-{v}-fast150.mp3')} | "
                    f"{play_if(f'audio/emotion/en-{v}-emotion.mp3')} | "
                    f"{play_if(f'audio/emotion/en-{v}-emotion-fast150.mp3')} |")
    return ("| voice | | full paragraph | 1.5× faster | with emotion | emotion 1.5× |\n"
            "|---|---|---|---|---|---|\n" + "\n".join(rows))


def korean_table() -> str:
    rows = []
    for p in sorted((ROOT / "audio/korean").glob("*.mp3")):
        emo = ROOT / "audio/emotion" / (p.stem.replace("el-", "ko-").replace("mai-", "ko-")
                                        .replace("gemini-", "ko-") + "-emotion.mp3")
        emo_alt = ROOT / "audio/emotion" / f"{p.stem}-emotion.mp3"
        emo_link = "—"
        for cand in (emo, emo_alt, ROOT / "audio/emotion/ko-kore-emotion.mp3"
                     if p.stem == "gemini-kore" else None):
            if cand and cand.exists():
                emo_link = play_if(cand.relative_to(ROOT).as_posix())
                break
        if p.stem == "mai-haena":
            emo_link = play_if("audio/emotion/ko-haena-plain.mp3") + " (plain: no emotion control)"
        rows.append(f"| {page_link(f'audio/korean/{p.name}', '`' + p.stem + '`')} | {play(f'audio/korean/{p.name}')} | {emo_link} |")
    return "| file | plain paragraph | with emotion |\n|---|---|---|\n" + "\n".join(rows)


def emotion_table() -> str:
    rows = []
    for p in sorted((ROOT / "audio/emotion").glob("*emotion.mp3")):
        rows.append(f"| {page_link(p.relative_to(ROOT).as_posix(), '`' + p.name + '`')} | {play(p.relative_to(ROOT).as_posix())} |")
    for name in ("_control_plain_sarah.mp3", "_control_plain_gemini.mp3"):
        p = ROOT / "audio/emotion" / name
        if p.exists():
            rows.append(f"| `{name}` (untagged control) | {play(p.relative_to(ROOT).as_posix())} |")
    return "| file | play |\n|---|---|\n" + "\n".join(rows)


def baselines_table() -> str:
    rows = []
    for d in ("audio/edge", "audio/elevenlabs-en-full", "audio/english"):
        for p in sorted((ROOT / d).glob("*.mp3")):
            rows.append(f"| {page_link(p.relative_to(ROOT).as_posix(), '`' + d + '/' + p.name + '`')} | {play(p.relative_to(ROOT).as_posix())} |")
    extra = [("audio/emotion/en-sarah-emotion.mp3", "the emotion version, for comparison"),
             ("audio/emotion/_control_plain_sarah.mp3", "untagged control of the same script")]
    for rel, note in extra:
        if (ROOT / rel).exists():
            rows.append(f"| {page_link(rel, '`' + rel + '`')} — {note} | {play(rel)} |")
    return "| file | play |\n|---|---|\n" + "\n".join(rows)


def local_table() -> str:
    rows = []
    for p in sorted((ROOT / "audio/local").glob("*.mp3")):
        rows.append(f"| {page_link(p.relative_to(ROOT).as_posix(), '`' + p.name + '`')} | {play(p.relative_to(ROOT).as_posix())} |")
    return "| file | play |\n|---|---|\n" + "\n".join(rows)


def special_table() -> str:
    rows = []
    for name in ("happy-birthday-to-bel-4part-harmony.mp3", "reference-synth-4parts.mp3"):
        p = ROOT / "audio/birthday" / name
        if p.exists():
            rows.append(f"| `{name}` | {play(p.relative_to(ROOT).as_posix())} |")
    return "| file | play |\n|---|---|\n" + "\n".join(rows)



def longtext_table() -> str:
    rows = []
    for p in sorted((ROOT / "audio/longtext").glob("*.mp3")):
        rows.append(f"| {page_link(p.relative_to(ROOT).as_posix(), '`' + p.name + '`')} | {play(p.relative_to(ROOT).as_posix())} |")
    if not rows:
        return ""
    return "\n".join(["| file | play |", "|---|---|", *rows])

def build() -> str:
    return "\n".join([
        BEGIN,
        "",
        f"> **Click any ▶ to play it immediately** (the browser opens its audio player) — or click the",
        f"> **name** for that sample's own page with the player in place, the text spoken, the STT",
        f"> transcript and the measurements. GitHub's markdown sanitiser strips embedded",
        f"> `<audio>`/`<video>` tags, its file page for an mp3 offers only a download, and",
        f"> raw.githubusercontent.com sends `content-disposition: attachment` — so the links point at",
        f"> jsDelivr, which serves `audio/mpeg` inline. A single page with every player:",
        f"> **[listening room]({PAGES})**.",
        ">",
        "> Generated by `tools_gen_catalog.py` (it refuses to emit a link to a missing file;",
        "> `tools_gen_players.py` writes the listening room). Regenerate both after adding samples.",
        "",
        "**Same paragraph, three ways**",
        "",
        baselines_table(),
        "",
        "**All 20 English premade voices** — full paragraph, 1.5× faster, and both with emotion",
        "",
        english_table(),
        "",
        f"**Korean** ({len(list((ROOT / 'audio/korean').glob('*.mp3')))} voices)",
        "",
        korean_table(),
        "",
        "**Local / offline engines** (no API key, $0)",
        "",
        local_table(),
        "",
        "**Special cases**",
        "",
        special_table(),
        "",
        "**Long text** — 3,813 characters (`samples/long-text-sample.txt`) rendered as one file, "
        "chunked on sentence boundaries with cross-chunk prosody. Stored at 64 kbps mono to stay "
        "under the repo's 2 MB binary guard; the STT round-trip still scores 0.995.",
        "",
        longtext_table(),
        "",
        "**Full emotion set** (all files, including the Korean renders and the English Gemini take)",
        "",
        emotion_table(),
        "",
        END,
    ])


def main() -> None:
    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit("README is missing the catalog markers")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), build(), text, flags=re.S)
    README.write_text(new, encoding="utf-8")
    # links are CDN URLs now; validate the repo-relative path inside each one
    links = re.findall(r"\]\(([^) ]+?)(?: [^)]+)?\)", new)
    rels = [l[len(CDN) + 1:] if l.startswith(CDN + "/") else l for l in links]
    rels = [l for l in rels if l.startswith(("audio/", "results/"))]
    missing = [l for l in rels if not (ROOT / l).exists()]
    print(f"catalog regenerated: {len(rels)} file links, {len(missing)} broken")
    for m in missing:
        print("  MISSING", m)
    if missing:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
